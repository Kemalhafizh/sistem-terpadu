<?php

use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;

/*
 * Every external script or stylesheet a view loads must be allowed by the
 * Content-Security-Policy the app actually sends. Otherwise the browser
 * silently blocks it in production: this is how the library QR labels, the
 * circulation scanner, the alumni map, the Midtrans popup and five
 * Tailwind-CDN pages ended up broken while every test stayed green.
 */

function cspSources(string $header, string $directive): array
{
    foreach (explode(';', $header) as $part) {
        $tokens = preg_split('/\s+/', trim($part));
        if (($tokens[0] ?? null) === $directive) {
            return array_slice($tokens, 1);
        }
    }

    return [];
}

function hostAllowed(string $url, array $sources): bool
{
    $origin = parse_url($url, PHP_URL_SCHEME).'://'.parse_url($url, PHP_URL_HOST);
    foreach ($sources as $source) {
        if ($source === $origin || (str_starts_with($source, 'https://*.') && str_ends_with($origin, substr($source, 9)))) {
            return true;
        }
    }

    return false;
}

test('every external script and stylesheet in the views is allowed by the CSP', function () {
    $csp = $this->get('/login')->headers->get('Content-Security-Policy');
    expect($csp)->not->toBeEmpty();
    $scriptSources = cspSources($csp, 'script-src');
    $styleSources = cspSources($csp, 'style-src');

    $violations = [];
    foreach (File::allFiles(resource_path('views')) as $file) {
        $path = Str::after($file->getPathname(), resource_path('views').DIRECTORY_SEPARATOR);
        // Generated by `php artisan scribe:generate`; overwritten on each run.
        if (str_starts_with($path, 'scribe'.DIRECTORY_SEPARATOR)) {
            continue;
        }
        $html = $file->getContents();

        preg_match_all('/<script[^>]+src=["\'](https?:\/\/[^"\']+)/i', $html, $scripts);
        preg_match_all('/script\w*\.src\s*=\s*[\'"](https?:\/\/[^\'"]+)/i', $html, $dynamicScripts);
        foreach (array_merge($scripts[1], $dynamicScripts[1]) as $url) {
            if (! hostAllowed($url, $scriptSources)) {
                $violations[] = "{$path}: script {$url}";
            }
        }

        preg_match_all('/<link[^>]+rel=["\']stylesheet["\'][^>]*href=["\'](https?:\/\/[^"\']+)|<link[^>]+href=["\'](https?:\/\/[^"\']+)["\'][^>]*rel=["\']stylesheet/i', $html, $styles);
        foreach (array_filter(array_merge($styles[1], $styles[2])) as $url) {
            if (! hostAllowed($url, $styleSources)) {
                $violations[] = "{$path}: stylesheet {$url}";
            }
        }
    }

    expect($violations)->toBe([]);
});

test('the Midtrans Snap popup and the web QR scanner are not blocked by headers', function () {
    $response = $this->get('/login');
    $csp = $response->headers->get('Content-Security-Policy');

    foreach (['https://app.midtrans.com', 'https://app.sandbox.midtrans.com'] as $snapHost) {
        expect(cspSources($csp, 'script-src'))->toContain($snapHost)
            ->and(cspSources($csp, 'frame-src'))->toContain($snapHost);
    }
    // library/circulation scans book QR codes with the device camera.
    expect($response->headers->get('Permissions-Policy'))->toContain('camera=(self)');
});

test('self-hosted libraries the views load actually exist', function () {
    foreach ([
        'vendor/qrcodejs-1.0.0/qrcode.min.js',
        'vendor/html5-qrcode-2.3.8/html5-qrcode.min.js',
        'vendor/html2canvas-1.4.1/html2canvas.min.js',
    ] as $asset) {
        expect(public_path($asset))->toBeFile();
    }
});
